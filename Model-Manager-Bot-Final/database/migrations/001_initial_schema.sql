-- Model Manager Bot — Supabase PostgreSQL
create extension if not exists pgcrypto;

create table if not exists public.guild_settings (
  guild_id text primary key,
  registration_channel_id text,
  models_channel_id text,
  featured_channel_id text,
  logs_channel_id text,
  register_role_id text,
  edit_role_id text,
  delete_role_id text,
  view_role_id text,
  credentials_role_id text,
  feature_role_id text,
  registration_message_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.models (
  id uuid primary key default gen_random_uuid(),
  guild_id text not null references public.guild_settings(guild_id) on delete cascade,
  public_id bigint generated by default as identity,
  name text not null,
  stage_name text not null,
  gmail text not null,
  facebook_name text not null,
  facebook_nick text not null,
  facebook_link text not null,
  facebook_email text not null,
  tiktok_name text not null,
  tiktok_nick text not null,
  tiktok_link text not null,
  tiktok_email text not null,
  instagram_name text not null,
  instagram_nick text not null,
  instagram_link text not null,
  instagram_email text not null,
  observations text,
  photo_path text not null,
  is_featured boolean not null default false,
  public_message_id text,
  featured_message_id text,
  created_by text not null,
  created_by_tag text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(guild_id, public_id),
  unique(guild_id, id)
);

create index if not exists models_guild_created_idx on public.models(guild_id, created_at desc);
create index if not exists models_guild_name_idx on public.models(guild_id, lower(name));
create index if not exists models_guild_stage_idx on public.models(guild_id, lower(stage_name));
create index if not exists models_guild_featured_idx on public.models(guild_id, is_featured);

create table if not exists public.model_secrets (
  model_id uuid primary key,
  guild_id text not null,
  gmail_password text not null,
  facebook_password text not null,
  tiktok_password text not null,
  instagram_password text not null,
  updated_at timestamptz not null default now(),
  constraint model_secrets_model_fk foreign key (guild_id, model_id)
    references public.models(guild_id, id) on delete cascade
);

create table if not exists public.audit_logs (
  id bigint generated always as identity primary key,
  guild_id text not null,
  actor_id text,
  actor_tag text,
  action text not null,
  model_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_guild_created_idx on public.audit_logs(guild_id, created_at desc);
create index if not exists audit_model_idx on public.audit_logs(model_id);

-- Bot usa service_role exclusivamente no servidor. RLS evita exposição por chaves anon/auth.
alter table public.guild_settings enable row level security;
alter table public.models enable row level security;
alter table public.model_secrets enable row level security;
alter table public.audit_logs enable row level security;

